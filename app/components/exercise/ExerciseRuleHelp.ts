import type { PedagogyNode, PedagogyState } from "./ExercisePedagogyTypes";

function weakLetterRule(target: string) {
  return `إذا كان آخر «${target}» ألفًا أو واوًا أو ياءً فهو معتل الآخر. حروف العلة هي: الألف، والواو، والياء، وهي التي تحدد ظهور الحركة أو تقديرها أو حذف حرف العلة.`;
}

export function exerciseRuleHelpText(
  node: PedagogyNode | null | undefined,
  state: PedagogyState,
  title = "",
): string {
  const id = String(node?.id || "");
  const target = String(state?.currentTarget || "المحدد");
  const sentence = String(state?.currentSentence || state?.sentence || "");
  const topic = `${title} ${id}`;

  if (/ending|weak/u.test(id)) return weakLetterRule(target);
  if (/five|khams|asmaa5/u.test(id)) {
    return "الأسماء الخمسة: أب، أخ، حم، فو، ذو. تُعرب بالحروف إذا كانت مفردة، مكبّرة، مضافة، ومضافة إلى غير ياء المتكلم: ترفع بالواو، وتنصب بالألف، وتجر بالياء.";
  }
  if (/masdar|source/u.test(id) || String(node?.text || "").includes("مصدر مؤول")) {
    return "المصدر المؤول تركيب في تأويل اسم، مثل «أن + فعل مضارع». جرّب تأويله بمصدر صريح، ثم أعطه موقع الاسم الذي حلّ محله في الجملة.";
  }
  if (/la_|لا النافية/u.test(topic)) {
    return "لا النافية للجنس تنفي الحكم عن جميع أفراد الجنس، وتعمل عمل إنَّ عند تحقق شروطها: تنصب اسمها وترفع خبرها. نوع اسمها قد يكون مفردًا، أو مضافًا، أو شبيهًا بالمضاف؛ والمقصود بـ«المفرد» هنا: غير المضاف وغير الشبيه بالمضاف.";
  }
  if (/munada|المنادى/u.test(topic)) {
    return "في المنادى نلاحظ الخصائص قبل المصطلح: العلم يدل على شخص معيّن باسمه، والنكرة المقصودة يقصد بها شخص معيّن، والمضاف يأتي بعده مضاف إليه، والشبيه بالمضاف يتم معناه بما بعده من غير إضافة، والنكرة غير المقصودة لا يراد بها فرد بعينه.";
  }
  if (/istithna|الاستثناء/u.test(topic)) {
    return "في الاستثناء المفرغ لا يكون ما بعد «إلا» مستثنى منصوبًا بالضرورة؛ احذف «إلا» ذهنيًا وأعرب ما بعدها حسب موقعه الذي يطلبه العامل: فاعلًا أو مفعولًا به أو اسمًا مجرورًا مثلًا.";
  }
  if (/tamyiz|التمييز/u.test(topic)) {
    return "التمييز يزيل إبهامًا. إن سبقته كمية أو مقدار أو عدد فهو غالبًا تمييز ملفوظ، وإن كان الإبهام في معنى الجملة كلها ثم جاءت الكلمة لتوضحه فهو تمييز ملحوظ.";
  }
  if (/hal|الحال/u.test(topic)) {
    return "الحال يبين هيئة صاحبه وقت وقوع الفعل. اسأل: كيف حدث الفعل؟ والجمل بعد المعارف تكون أحوالًا إذا بينت الهيئة وتحقق الرابط، أما الجمل بعد النكرات فتكون صفات إذا وصفتها.";
  }
  if (/tawabi|naat|badal|atf|tawkid|النعت|البدل|العطف|التوكيد/u.test(topic)) {
    return "التابع يتبع متبوعه في الحالة الإعرابية، وليس شرطًا أن تتطابق علامة الإعراب. حدد العلاقة أولًا: وصف = نعت، حرف عطف = عطف، تقوية للمعنى = توكيد، أو اسم هو المقصود بالحكم/جزء أو معنى مرتبط = بدل؛ ثم انقل الحالة وحدد علامة التابع من صورته هو.";
  }
  if (/mafoolat|مفعول مطلق|مفعول معه/u.test(topic)) {
    return "في المفاعيل نثبت العلاقة من المعنى قبل العلامة: واو بمعنى «مع» تقود إلى المفعول معه، ومصدر من معنى الفعل يؤكده أو يبين نوعه أو عدده يقود إلى المفعول المطلق، والاسم الذي يبين سبب الفعل قد يكون مفعولًا لأجله، وما يدل على زمان أو مكان قد يكون ظرفًا.";
  }
  if (/mafool|المفعول به/u.test(topic)) {
    return `لإثبات المفعول به اسأل: على من أو على ماذا وقع فعل الجملة مباشرة؟ بعد ثبوت الوظيفة يكون المفعول به منصوبًا، ثم نحدد علامة النصب من صورة «${target}».`;
  }
  if (/naib|نائب الفاعل/u.test(topic)) {
    return `في المبني للمجهول نحذف الفاعل ويأخذ الاسم الذي ناب عنه حكم الرفع. اسأل عن «${target}»: ما الذي وقع عليه الفعل بعد حذف فاعله؟ ثم حدد صورته وعلامة رفعه.`;
  }
  if (/fael|الفاعل/u.test(topic)) {
    return `لإثبات الفاعل اسأل من الجملة نفسها: من الذي قام بالفعل؟ وقد يكون اسمًا ظاهرًا، أو ضميرًا متصلًا، أو ضميرًا مستترًا. الفاعل مرفوع أو في محل رفع إن كان مبنيًا.`;
  }
  if (/inna|إن وأخواتها/u.test(topic)) {
    return "في إنَّ وأخواتها نتحقق أولًا من «ما» الكافة. إن لم تكفّ الحرف عن العمل فإنه ينصب اسمه ويرفع خبره. وبعد ثبوت أن الاسم مبني نحدد نوعه من المبنيات في خطوة مستقلة.";
  }
  if (/kana|كان وأخواتها/u.test(topic)) {
    return "كان وأخواتها أفعال ناسخة: ترفع الاسم وتنصب الخبر. نربط كل سؤال بالفعل الناسخ الظاهر في المثال، ثم نحدد وظيفة المحدد وصورته وعلامته من غير قفز.";
  }
  if (/imperative|الأمر/u.test(topic)) {
    return `فعل الأمر مبني. عند الحاجة إلى كشف أصله نرده إلى المضارع مع ضمير مناسب؛ مثل «اكتبي» ← «أنتِ تكتبين»، فتظهر النون ثم نلاحظ حذفها في الأمر.`;
  }
  if (/present|المضارع/u.test(topic)) {
    return `المضارع معرب في الأصل إلا مع نون النسوة أو نون التوكيد المباشرة. بعد فحص البناء نبحث عن العامل السابق، ثم نحدد صورة آخر الفعل. ${weakLetterRule(target)}`;
  }
  if (/past|الماضي/u.test(topic)) {
    return "الفعل الماضي مبني دائمًا. نحدد أولًا أنه ماضٍ، ثم نفحص ما اتصل بآخره: ضمير رفع متحرك يقود إلى السكون، وواو الجماعة إلى الضم، وألف الاثنين تبقيه على الفتح، مع مراعاة الفعل الناقص.";
  }
  if (/khabar|الخبر/u.test(topic)) {
    return "الخبر هو المعلومة التي تتم المعنى عن المبتدأ. وقد يكون مفردًا، أو جملة فعلية/اسمية، أو شبه جملة. إذا كان تركيبًا كاملًا فالمطلوب هو التركيب كله، لا كلمة منه فقط.";
  }
  if (/mubtada|المبتدأ/u.test(topic)) {
    return "المبتدأ اسم نبدأ به غالبًا الكلام ونبدأ الحديث عنه. بعد ثبوت الوظيفة نحدد هل المحدد اسم معرب أم مبني، أو تركيب في تأويل اسم، ثم نحدد الصورة والعلامة.";
  }

  return sentence
    ? `راجع القاعدة المرتبطة بالسؤال الحالي في الجملة «${sentence}»: اثبت العلاقة أو الوظيفة أولًا، ثم الحالة الإعرابية، ثم الصورة والعلامة، ولا تنتقل إلى النتيجة قبل تثبيت الخطوة الحالية.`
    : "اثبت العلاقة أو الوظيفة أولًا، ثم الحالة الإعرابية، ثم صورة الكلمة وعلامتها. لا تنتقل إلى النتيجة قبل تثبيت الخطوة الحالية.";
}
