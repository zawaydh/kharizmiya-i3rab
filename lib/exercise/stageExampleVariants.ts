function replaceDeep(value: unknown, from: string, to: string): unknown {
  if (typeof value === "string") return value.split(from).join(to);
  if (Array.isArray(value)) return value.map((item) => replaceDeep(item, from, to));
  if (!value || typeof value !== "object") return value;
  const out: Record<string, unknown> = {};
  for (const [key, child] of Object.entries(value as Record<string, unknown>)) {
    out[key] = key === "id" || key === "covers" ? child : replaceDeep(child, from, to);
  }
  return out;
}

function chooseReplacement(example: ExerciseExample, replacements: readonly Replacement[]) {
  const sentence = String(example.sentence || "");
  return replacements.find(([from, to]) =>
    sentence.includes(from) && (from === to || !sentence.includes(to)),
  );
}

export function stageExampleVariant<T extends ExerciseExample>(example: T, mode: Mode): T {
  if (mode === "learn") return example;
  const replacement = chooseReplacement(
    example,
    mode === "practice" ? PRACTICE_REPLACEMENTS : QUIZ_REPLACEMENTS,
  );
  if (!replacement) return example;
  const [from, to] = replacement;
  const varied = replaceDeep(example, from, to) as T;
  // الهوية ومفاتيح التغطية لا تتغير؛ بقية النصوص تتغير مع اللفظة البديلة كي تبقى متسقة.
  varied.id = example.id;
  varied.covers = example.covers;
  return varied;
}

export function stageExampleVariants<T extends ExerciseExample>(examples: readonly T[], mode: Mode): T[] {
  return examples.map((example) => stageExampleVariant(example, mode));
}
